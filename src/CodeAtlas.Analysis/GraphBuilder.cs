using CodeAtlas.Core;
using Microsoft.CodeAnalysis;

namespace CodeAtlas.Analysis;

/// <summary>
/// Accumulates types and dependencies from one or more compilations, then produces a
/// <see cref="DependencyGraph"/>.
/// </summary>
/// <remarks>
/// Edges are collected as candidates and only kept in <see cref="Build"/>, once every compilation
/// has been added. A project may reference a type from a project that has not been added yet, so
/// we can't tell "external library type" from "solution type" until the end.
/// </remarks>
/// <param name="rootDirectory">When set, source paths under it are written relative to it.</param>
public sealed class GraphBuilder(string? rootDirectory = null)
{
    private readonly Dictionary<string, CodeNode> _nodes = new(StringComparer.Ordinal);
    private readonly Dictionary<(string Source, string Target, DependencyKind Kind), CodeEdge> _candidateEdges = [];
    private readonly HashSet<string> _unresolvedTypes = new(StringComparer.Ordinal);
    private readonly List<string> _warnings = [];

    public void AddWarning(string message) => _warnings.Add(message);

    /// <param name="projectName">Label for the nodes' project. Defaults to the assembly name.</param>
    public void AddCompilation(Compilation compilation, string? projectName = null)
    {
        var project = projectName ?? compilation.AssemblyName ?? "(unnamed)";

        // Creating a semantic model is expensive and a file can declare many types, so share one per file.
        var semanticModels = new Dictionary<SyntaxTree, SemanticModel>();
        SemanticModel SemanticModelFor(SyntaxTree tree)
        {
            if (!semanticModels.TryGetValue(tree, out var model))
            {
                model = compilation.GetSemanticModel(tree);
                semanticModels[tree] = model;
            }

            return model;
        }

        foreach (var type in SourceTypes(compilation.Assembly.GlobalNamespace))
        {
            // Build tooling can inject source from outside the solution (e.g. the test SDK's
            // AutoGeneratedProgram lives in the NuGet cache). That code isn't part of the solution.
            if (rootDirectory is not null && !type.Locations.Any(IsUnderRoot))
            {
                continue;
            }

            var sourceId = SymbolIds.For(type);

            // A multi-targeted project appears once per target framework. Keep the first copy.
            if (!_nodes.TryAdd(sourceId, CreateNode(sourceId, type, project)))
            {
                continue;
            }

            var references = DependencyExtractor.Extract(type)
                .Concat(BodyDependencyExtractor.Extract(type, SemanticModelFor));

            foreach (var reference in references)
            {
                foreach (var target in DependencyExtractor.Flatten(reference.Type))
                {
                    if (target.TypeKind == TypeKind.Error)
                    {
                        _unresolvedTypes.Add(target.ToDisplayString());
                        continue;
                    }

                    var targetId = SymbolIds.For(target);
                    if (targetId == sourceId)
                    {
                        continue;
                    }

                    _candidateEdges.TryAdd(
                        (sourceId, targetId, reference.Kind),
                        new CodeEdge(sourceId, targetId, reference.Kind, ToSourceLocation(reference.Location)));
                }
            }
        }
    }

    public DependencyGraph Build()
    {
        var warnings = new List<string>(_warnings);
        if (_unresolvedTypes.Count > 0)
        {
            var sample = string.Join(", ", _unresolvedTypes.Order(StringComparer.Ordinal).Take(5));
            warnings.Add(
                $"{_unresolvedTypes.Count} referenced type(s) could not be resolved (e.g. {sample}). " +
                "Dependencies through them were skipped. Restoring or building the solution usually fixes this.");
        }

        return new DependencyGraph
        {
            Nodes = _nodes.Values.OrderBy(n => n.Id, StringComparer.Ordinal).ToList(),
            Edges = _candidateEdges.Values
                .Where(e => _nodes.ContainsKey(e.TargetId))
                .OrderBy(e => e.SourceId, StringComparer.Ordinal)
                .ThenBy(e => e.TargetId, StringComparer.Ordinal)
                .ThenBy(e => e.Kind)
                .ToList(),
            Warnings = warnings,
        };
    }

    /// <summary>Walks symbols rather than syntax, so each partial type is visited exactly once.</summary>
    private static IEnumerable<INamedTypeSymbol> SourceTypes(INamespaceSymbol @namespace)
    {
        foreach (var member in @namespace.GetMembers())
        {
            var types = member switch
            {
                INamespaceSymbol child => SourceTypes(child),
                INamedTypeSymbol type => WithNestedTypes(type),
                _ => [],
            };

            foreach (var type in types)
            {
                yield return type;
            }
        }
    }

    private static IEnumerable<INamedTypeSymbol> WithNestedTypes(INamedTypeSymbol type)
    {
        if (!type.Locations.Any(l => l.IsInSource))
        {
            yield break;
        }

        yield return type;

        foreach (var nested in type.GetTypeMembers())
        {
            foreach (var inner in WithNestedTypes(nested))
            {
                yield return inner;
            }
        }
    }

    private CodeNode CreateNode(string id, INamedTypeSymbol type, string project) => new(
        Id: id,
        Name: type.ToDisplayString(SymbolDisplayFormat.MinimallyQualifiedFormat),
        FullName: type.ToDisplayString(),
        Namespace: type.ContainingNamespace.IsGlobalNamespace ? "" : type.ContainingNamespace.ToDisplayString(),
        Project: project,
        Kind: KindOf(type),
        Locations: type.Locations
            .Select(ToSourceLocation)
            .OfType<SourceLocation>()
            .ToList());

    private static NodeKind KindOf(INamedTypeSymbol type) => type switch
    {
        { TypeKind: TypeKind.Interface } => NodeKind.Interface,
        { TypeKind: TypeKind.Enum } => NodeKind.Enum,
        { TypeKind: TypeKind.Delegate } => NodeKind.Delegate,
        { TypeKind: TypeKind.Struct, IsRecord: true } => NodeKind.RecordStruct,
        { TypeKind: TypeKind.Struct } => NodeKind.Struct,
        { IsRecord: true } => NodeKind.Record,
        _ => NodeKind.Class,
    };

    private SourceLocation? ToSourceLocation(Location? location)
    {
        if (location is null || !location.IsInSource)
        {
            return null;
        }

        var span = location.GetLineSpan();
        var path = RelativeToRoot(span.Path) ?? span.Path;
        return new SourceLocation(path.Replace('\\', '/'), span.StartLinePosition.Line + 1);
    }

    private bool IsUnderRoot(Location location) =>
        location.IsInSource && RelativeToRoot(location.GetLineSpan().Path) is not null;

    /// <summary>Returns <paramref name="path"/> relative to the root directory, or null if it lies outside it.</summary>
    private string? RelativeToRoot(string path)
    {
        if (rootDirectory is null || !Path.IsPathRooted(path))
        {
            return null;
        }

        var relative = Path.GetRelativePath(rootDirectory, path);
        return relative.StartsWith("..", StringComparison.Ordinal) || Path.IsPathRooted(relative) ? null : relative;
    }
}
