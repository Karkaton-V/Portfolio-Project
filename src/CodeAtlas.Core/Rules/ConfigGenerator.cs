using System.Text;
using System.Text.Json;

namespace CodeAtlas.Core.Rules;

/// <param name="Json">The <c>codeatlas.json</c> text, with comments explaining each part.</param>
/// <param name="Layers">Layer name to the projects assigned to it, in dependency order (innermost first).</param>
/// <param name="Unassigned">Projects whose names didn't match any layer convention.</param>
public sealed record GeneratedConfig(
    string Json,
    IReadOnlyList<(string Layer, IReadOnlyList<string> Projects)> Layers,
    IReadOnlyList<string> Unassigned,
    int RuleCount);

/// <summary>
/// Writes a starter <c>codeatlas.json</c> for any solution (<c>burndown init</c>). Projects are sorted into
/// layers by the naming conventions most .NET solutions follow (Domain/Core, Application/Services,
/// Infrastructure/Persistence/Data, Web/Api/UI, and test projects), then the usual layering rules are written
/// for the layers that exist. It's a starting point: the comments tell the reader what to review.
/// </summary>
public static class ConfigGenerator
{
    // Innermost layer first. A project matches a layer when any dot-separated part of its name is one of the words.
    private static readonly (string Layer, string[] Words)[] Conventions =
    [
        ("Domain", ["Domain", "Core", "Entities", "Model", "Models", "Kernel", "SharedKernel"]),
        ("Application", ["Application", "App", "Services", "UseCases", "Business", "Logic", "Features"]),
        ("Infrastructure", ["Infrastructure", "Infra", "Persistence", "Data", "DataAccess", "Repositories", "Integrations"]),
        ("Presentation", ["Web", "Api", "WebApi", "Presentation", "UI", "Mvc", "Blazor", "Server", "Host", "Client", "Gateway", "Functions"]),
    ];

    private static readonly string[] TestSuffixes = ["Tests", "Test", "Specs", "Spec", "Benchmarks"];

    public static GeneratedConfig Generate(DependencyGraph graph, string solutionName)
    {
        var projects = graph.Nodes.Select(n => n.Project).Distinct().Order(StringComparer.OrdinalIgnoreCase).ToList();

        var tests = projects.Where(IsTestProject).ToList();
        var production = projects.Except(tests).ToList();
        var assigned = Conventions
            .Select(c => (c.Layer, Projects: (IReadOnlyList<string>)production.Where(p => LayerOf(p) == c.Layer).ToList()))
            .Where(l => l.Projects.Count > 0)
            .ToList();
        if (tests.Count > 0)
        {
            assigned.Add(("Tests", tests));
        }

        var unassigned = production.Where(p => LayerOf(p) is null).ToList();
        var has = assigned.Select(l => l.Layer).ToHashSet();

        var rules = new List<string>();
        if (has.Contains("Domain"))
        {
            rules.Add(Rule("Domain depends on nothing else", "Domain", "mayOnlyDependOn", []));
        }

        if (has.Contains("Application"))
        {
            rules.Add(Rule(
                has.Contains("Domain") ? "Application depends only on Domain" : "Application depends on nothing else",
                "Application", "mayOnlyDependOn", has.Contains("Domain") ? ["Domain"] : []));
        }

        if (has.Contains("Infrastructure") && has.Contains("Presentation"))
        {
            rules.Add(Rule("Infrastructure does not depend on Presentation", "Infrastructure", "forbid", ["Presentation"]));
        }

        if (tests.Count > 0 && production.Count > 0)
        {
            rules.Add(Rule("Production code does not depend on tests", "Production", "forbid", ["Tests"]));
        }

        var json = new StringBuilder();
        json.AppendLine("{");
        json.AppendLine($"  // Generated by `burndown init` for {solutionName}.");
        json.AppendLine("  // Layers were guessed from project names: review them, then run `burndown check`.");
        json.AppendLine("  // A layer lists selectors: \"project:Name\" selects a project, \"My.Namespace.**\" a namespace and");
        json.AppendLine("  // everything under it. See the README's \"Architecture rules\" section for every option.");
        if (unassigned.Count > 0)
        {
            json.AppendLine($"  // Not assigned to a layer (add them where they belong): {string.Join(", ", unassigned)}");
        }

        json.AppendLine();
        json.AppendLine("  \"layers\": {");
        var layerLines = assigned.Select(l => $"    {Quote(l.Layer)}: [{string.Join(", ", l.Projects.Select(p => Quote("project:" + p)))}]").ToList();
        if (tests.Count > 0 && production.Count > 0)
        {
            layerLines.Add($"    \"Production\": [{string.Join(", ", production.Select(p => Quote("project:" + p)))}]");
        }

        json.AppendLine(string.Join("," + Environment.NewLine, layerLines));
        json.AppendLine("  },");
        json.AppendLine();
        json.AppendLine("  \"rules\": [");
        if (rules.Count == 0)
        {
            json.AppendLine("    // No layers were recognized, so there are no layering rules yet. For example:");
            json.AppendLine("    // { \"name\": \"Core depends on nothing else\", \"from\": \"project:MyApp.Core\", \"mayOnlyDependOn\": [] }");
        }
        else
        {
            json.AppendLine(string.Join("," + Environment.NewLine, rules));
        }

        json.AppendLine("  ],");
        json.AppendLine();
        json.AppendLine("  // Report namespaces that depend on each other in a loop. Some cycles are deliberate (e.g. domain");
        json.AppendLine("  // events that carry their entity), so this starts as a warning; change it to \"error\" to enforce it.");
        json.AppendLine("  \"namespaceCycles\": \"warning\",");
        json.AppendLine();
        json.AppendLine("  // Projects to leave out of every command, e.g. [\"*Tests\", \"Samples.*\"].");
        json.AppendLine("  \"exclude\": [],");
        json.AppendLine();
        json.AppendLine($"  // Report theme: {string.Join(", ", ReportThemes.Names)}. Viewers can switch in the report too.");
        json.AppendLine($"  \"report\": {{ \"title\": {Quote(solutionName)}, \"theme\": {Quote(ReportThemes.Default)} }}");
        json.AppendLine("}");

        return new GeneratedConfig(json.ToString(), assigned, unassigned, rules.Count);
    }

    /// <summary>The layer a production project's name suggests, or null. The most specific (last) name part wins.</summary>
    internal static string? LayerOf(string project)
    {
        foreach (var part in project.Split('.').Reverse())
        {
            foreach (var (layer, words) in Conventions)
            {
                if (words.Contains(part, StringComparer.OrdinalIgnoreCase))
                {
                    return layer;
                }
            }
        }

        return null;
    }

    internal static bool IsTestProject(string project) =>
        TestSuffixes.Any(suffix => project.EndsWith(suffix, StringComparison.OrdinalIgnoreCase));

    private static string Rule(string name, string from, string kind, string[] targets) =>
        $"    {{ \"name\": {Quote(name)}, \"from\": {Quote(from)}, {Quote(kind)}: [{string.Join(", ", targets.Select(Quote))}] }}";

    private static string Quote(string value) => JsonSerializer.Serialize(value);
}
